def read_csv_safely(path: Path) -> pd.DataFrame:
    """utf-8-sig 우선, 실패 시 cp949로 CSV 로드."""
    path = Path(path)
    try:
        return pd.read_csv(path, encoding="utf-8-sig")
    except UnicodeDecodeError:
        return pd.read_csv(path, encoding="cp949")


def save_csv_safely(df: pd.DataFrame, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False, encoding="utf-8-sig")


def clean_text(text) -> str:
    """특수기호 제거 + 공백 정리. 한글/영문/숫자/공백만 남김."""
    if pd.isna(text):
        return ""
    text = re.sub(r"[^가-힣A-Za-z0-9\s]", " ", str(text))
    text = re.sub(r"\s+", " ", text).strip()
    return text


def split_text_to_chunks(text: str, max_chars: int = 1200, overlap_chars: int = 120) -> List[str]:
    """
    긴 full_text를 청크로 분리.
    - 문장 경계를 우선 사용
    - 너무 긴 문장은 max_chars 기준으로 자름
    """
    text = str(text or "").strip()
    if not text:
        return []

    sentences = re.split(r"(?<=[.!?。])\s+|(?<=다\.)\s+|\n+",text)
    sentences = [s.strip() for s in sentences if s and s.strip()]

    chunks = []
    current = ""

    def flush_current():
        nonlocal current
        if current.strip():
            chunks.append(current.strip())
            current = ""

    for sent in sentences:
        if len(sent) > max_chars:
            flush_current()
            step = max(1, max_chars - overlap_chars)
            for i in range(0, len(sent), step):
                chunks.append(sent[i:i + max_chars].strip())
            continue

        if len(current) + len(sent) + 1 <= max_chars:
            current = (current + " " + sent).strip()
        else:
            flush_current()
            current = sent

    flush_current()
    return chunks


def generate_ngrams(tokens: List[str], n: int) -> List[str]:
    return ["".join(tokens[i:i + n]) for i in range(len(tokens) - n + 1)]


def normalize_stopwords(extra_stopwords: Optional[Iterable[str]] = None) -> set:
    stopword_set = {str(w).lower().strip() for w in DEFAULT_STOPWORDS if str(w).strip()}
    if extra_stopwords:
        stopword_set.update({str(w).lower().strip() for w in extra_stopwords if str(w).strip()})
    return stopword_set


def load_extra_stopwords(stopword_path: Optional[Path]) -> List[str]:
    """추가 불용어 사전 CSV/TXT 로드. 컬럼명이 있으면 첫 컬럼 사용."""
    if not stopword_path:
        return []
    stopword_path = Path(stopword_path)
    if not stopword_path.exists():
        raise FileNotFoundError(f"추가 불용어 파일이 없습니다: {stopword_path}")

    if stopword_path.suffix.lower() in [".csv"]:
        df = read_csv_safely(stopword_path)
        if df.empty:
            return []
        return df.iloc[:, 0].dropna().astype(str).tolist()

    return [line.strip() for line in stopword_path.read_text(encoding="utf-8").splitlines() if line.strip()]


