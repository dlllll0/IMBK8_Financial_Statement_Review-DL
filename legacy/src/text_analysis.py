def build_kiwi_analyzer(
    custom_words: Optional[Iterable[str]] = None,
    ngram_words: Optional[Iterable[str]] = None,
):
    if Kiwi is None:
        raise ImportError(
            "kiwipiepy import 실패. 먼저 설치 필요: pip install kiwipiepy\n"
            f"원인: {KIWI_IMPORT_ERROR}"
        )

    kiwi = Kiwi()

    for word in DEFAULT_K_IFRS_MASTER:
        try:
            kiwi.add_user_word(str(word), "NNG")
        except Exception:
            pass

    for word in custom_words or []:
        if pd.notna(word) and str(word).strip():
            try:
                kiwi.add_user_word(str(word).strip(), "NNG")
            except Exception:
                pass

    for word in ngram_words or []:
        if pd.notna(word) and str(word).strip():
            try:
                kiwi.add_user_word(str(word).strip(), "NNG")
            except Exception:
                pass

    return kiwi


def tokenize_nouns_with_pos(text: str, kiwi, stopword_set: set) -> List[Tuple[str, str]]:
    """명사 계열(NN*)만 추출하고 불용어/숫자/1글자 제거."""
    if not text:
        return []

    tokens = kiwi.tokenize(text)
    out = []

    for token in tokens:
        word = str(token.form).strip()
        pos = str(token.tag).strip()

        if not pos.startswith("NN"):
            continue
        if not word or len(word) <= 1:
            continue
        if word.isdigit():
            continue
        if word.lower() in stopword_set:
            continue

        out.append((word, pos))

    return out


