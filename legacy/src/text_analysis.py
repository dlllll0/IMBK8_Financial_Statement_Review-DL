def find_fulltext_csvs(base_dir: Path) -> Dict[str, List[Path]]:
    """
    base_dir 아래에서 notes/audit/correction fulltext CSV를 찾는다.
    text_ocr.py 출력 파일명: TEXT_t_xxx_notes_fulltext_data.csv 형태를 가정.
    """
    base_dir = Path(base_dir)
    found = {key: [] for key in SOURCE_CONFIG}

    for source, cfg in SOURCE_CONFIG.items():
        pattern = f"*{cfg['input_key']}*.csv"
        found[source] = sorted(base_dir.rglob(pattern))

    return found


def collect_input_rows(input_files: Dict[str, List[Path]]) -> pd.DataFrame:
    """여러 fulltext CSV를 하나의 메타+텍스트 DataFrame으로 수집."""
    rows = []

    for source, files in input_files.items():
        for path in files:
            df = read_csv_safely(path)
            if "full_text" not in df.columns:
                continue

            for idx, row in df.iterrows():
                full_text = row.get("full_text", "")
                if pd.isna(full_text) or not str(full_text).strip():
                    continue

                rows.append({
                    "source": source,
                    "input_path": str(path),
                    "input_row_id": idx,
                    "job_id": row.get("job_id", ""),
                    "period_type": row.get("period_type", ""),
                    "file_name": row.get("file_name", path.name),
                    "industry": row.get("industry", ""),
                    "data_type": row.get("data_type", ""),
                    "report_type": row.get("report_type", ""),
                    "section_type": row.get("section_type", ""),
                    "section_title": row.get("section_title", ""),
                    "output_section_type": row.get("output_section_type", ""),
                    "full_text": str(full_text),
                })

    return pd.DataFrame(rows)


def build_global_ngram_dictionary(
    rows_df: pd.DataFrame,
    kiwi,
    stopword_set: set,
    threshold: int = 10,
    min_n: int = 2,
    max_n: int = 5,
) -> Dict[str, str]:
    """전체 입력 텍스트 기준 빈도 threshold 이상 N-gram을 사용자 사전에 등록할 후보로 생성."""
    if rows_df.empty:
        return {}

    global_tokens: List[str] = []

    for text in rows_df["full_text"]:
        cleaned = clean_text(text)
        if not cleaned:
            continue
        global_tokens.extend([word for word, _pos in tokenize_nouns_with_pos(cleaned, kiwi, stopword_set)])

    custom_ngram_tags: Dict[str, str] = {}

    for n in range(min_n, max_n + 1):
        ngrams = generate_ngrams(global_tokens, n)
        ngram_counts = Counter(ngrams)
        for ngram, count in ngram_counts.items():
            if count >= threshold:
                custom_ngram_tags[ngram] = f"{n}gram_Noun"

    return custom_ngram_tags


# =========================================================
# 5. 문서별 noun_data 생성
# =========================================================

def analyze_fulltext_rows(
    rows_df: pd.DataFrame,
    kiwi,
    stopword_set: set,
    custom_ngram_tags: Optional[Dict[str, str]] = None,
    chunk_size: int = 1200,
    chunk_overlap: int = 120,
) -> Dict[str, pd.DataFrame]:
    """
    fulltext rows를 source별 noun_data로 변환.
    결과는 단어 단위 long-format.
    """
    custom_ngram_tags = custom_ngram_tags or {}
    result_rows = {source: [] for source in SOURCE_CONFIG}

    if rows_df.empty:
        return {cfg["output_key"]: pd.DataFrame() for cfg in SOURCE_CONFIG.values()}

    for _row_idx, row in rows_df.iterrows():
        source = row["source"]
        if source not in result_rows:
            continue

        chunks = split_text_to_chunks(
            row.get("full_text", ""),
            max_chars=chunk_size,
            overlap_chars=chunk_overlap,
        )

        for chunk_idx, chunk in enumerate(chunks):
            clean_chunk = clean_text(chunk)
            if not clean_chunk:
                continue

            nouns_with_pos = tokenize_nouns_with_pos(clean_chunk, kiwi, stopword_set)
            if not nouns_with_pos:
                continue

            chunk_counter = Counter([w for w, _p in nouns_with_pos])
            first_pos = {}
            for w, p in nouns_with_pos:
                first_pos.setdefault(w, p)

            for word, count in chunk_counter.items():
                pos = first_pos.get(word, "")
                if word in custom_ngram_tags:
                    pos = custom_ngram_tags[word]
                elif word in DEFAULT_K_IFRS_MASTER:
                    pos = "IFRS_Noun"

                result_rows[source].append({
                    "job_id": row.get("job_id", ""),
                    "period_type": row.get("period_type", ""),
                    "source_type": source,
                    "file_name": row.get("file_name", ""),
                    "industry": row.get("industry", ""),
                    "data_type": row.get("data_type", ""),
                    "report_type": row.get("report_type", ""),
                    "section_type": row.get("section_type", ""),
                    "section_title": row.get("section_title", ""),
                    "output_section_type": row.get("output_section_type", ""),
                    "input_path": row.get("input_path", ""),
                    "input_row_id": row.get("input_row_id", ""),
                    "chunk_id": chunk_idx,
                    "chunk_text": clean_chunk,
                    "chunk_text_preview": clean_chunk[:300],
                    "word": word,
                    "pos": pos,
                    "word_count_in_chunk": int(count),
                    "chunk_noun_count": int(len(nouns_with_pos)),
                })

    output = {}
    for source, rows in result_rows.items():
        output_key = SOURCE_CONFIG[source]["output_key"]
        df = pd.DataFrame(rows)
        if not df.empty:
            # 문서 전체 단어 빈도, 청크 등장 수를 추가해두면 SQL 없이도 바로 비교 가능
            group_cols = ["job_id", "period_type", "source_type", "file_name", "word"]
            total_counts = (
                df.groupby(group_cols, dropna=False)["word_count_in_chunk"]
                .sum()
                .reset_index()
                .rename(columns={"word_count_in_chunk": "word_total_count_in_doc"})
            )
            chunk_counts = (
                df.groupby(group_cols, dropna=False)["chunk_id"]
                .nunique()
                .reset_index()
                .rename(columns={"chunk_id": "word_included_chunk_count"})
            )
            df = df.merge(total_counts, on=group_cols, how="left")
            df = df.merge(chunk_counts, on=group_cols, how="left")

            front_cols = [
                "job_id", "period_type", "source_type", "file_name", "industry", "data_type", "report_type",
                "section_type", "section_title", "output_section_type", "chunk_id", "word", "pos",
                "word_count_in_chunk", "word_total_count_in_doc", "word_included_chunk_count",
                "chunk_noun_count", "chunk_text_preview", "chunk_text", "input_path", "input_row_id",
            ]
            df = df[[c for c in front_cols if c in df.columns] + [c for c in df.columns if c not in front_cols]]
            df = df.sort_values(
                by=["file_name", "chunk_id", "word_total_count_in_doc", "word"],
                ascending=[True, True, False, True],
            ).reset_index(drop=True)

        output[output_key] = df

    return output


