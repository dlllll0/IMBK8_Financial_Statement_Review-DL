def parse_args():
    parser = argparse.ArgumentParser(description="OCR fulltext CSV 명사 분석")
    parser.add_argument("--input-dir", default=None, help="분석할 text OCR 결과 폴더")
    parser.add_argument("--output-dir", default=None, help="저장할 text_analysis 결과 폴더")
    parser.add_argument("--job-id", default=None, help="outputs/jobs/{job_id} 기준으로 t/t-1 모두 분석")
    parser.add_argument("--jobs-output-dir", default="outputs/jobs", help="jobs output root")
    parser.add_argument("--stopword-path", default=None, help="추가 불용어 CSV/TXT")
    parser.add_argument("--custom-word-path", default=None, help="추가 사용자사전 CSV/TXT")
    parser.add_argument("--ngram-threshold", type=int, default=10)
    parser.add_argument("--chunk-size", type=int, default=1200)
    parser.add_argument("--chunk-overlap", type=int, default=120)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()

    common_kwargs = dict(
        stopword_path=Path(args.stopword_path) if args.stopword_path else None,
        custom_word_path=Path(args.custom_word_path) if args.custom_word_path else None,
        ngram_threshold=args.ngram_threshold,
        chunk_size=args.chunk_size,
        chunk_overlap=args.chunk_overlap,
        save_output=True,
    )

    if args.job_id:
        run_text_analysis_for_job(
            job_id=args.job_id,
            jobs_output_dir=Path(args.jobs_output_dir),
            **common_kwargs,
        )
    else:
        if not args.input_dir or not args.output_dir:
            raise ValueError("--job-id 또는 --input-dir/--output-dir를 지정해야 합니다.")
        run_text_analysis(
            input_dir=Path(args.input_dir),
            output_dir=Path(args.output_dir),
            **common_kwargs,
        )
