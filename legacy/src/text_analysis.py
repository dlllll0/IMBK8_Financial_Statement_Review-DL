def run_text_analysis(
    input_dir: Path,
    output_dir: Path,
    stopword_path: Optional[Path] = None,
    custom_word_path: Optional[Path] = None,
    ngram_threshold: int = 10,
    chunk_size: int = 1200,
    chunk_overlap: int = 120,
    save_output: bool = True,
) -> Dict[str, pd.DataFrame]:
    """
    특정 폴더 안의 notes/audit/correction fulltext CSV를 찾아 명사 데이터 생성.
    period_type은 입력 CSV에 들어있는 값을 그대로 사용한다.
    """
    input_dir = Path(input_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 100)
    print("[TEXT ANALYSIS START]")
    print("input_dir:", input_dir)
    print("output_dir:", output_dir)
    print("=" * 100)

    input_files = find_fulltext_csvs(input_dir)
    for source, files in input_files.items():
        print(f"- {source} input files: {len(files)}")

    rows_df = collect_input_rows(input_files)
    print("수집된 full_text row 수:", rows_df.shape)

    if rows_df.empty:
        print("[경고] 분석할 full_text가 없습니다.")
        empty_result = {cfg["output_key"]: pd.DataFrame() for cfg in SOURCE_CONFIG.values()}
        return empty_result

    extra_stopwords = load_extra_stopwords(stopword_path)
    stopword_set = normalize_stopwords(extra_stopwords)

    custom_words = []
    if custom_word_path:
        custom_word_path = Path(custom_word_path)
        if custom_word_path.exists():
            if custom_word_path.suffix.lower() == ".csv":
                custom_words = read_csv_safely(custom_word_path).iloc[:, 0].dropna().astype(str).tolist()
            else:
                custom_words = [line.strip() for line in custom_word_path.read_text(encoding="utf-8").splitlines() if line.strip()]

    kiwi_base = build_kiwi_analyzer(custom_words=custom_words)

    print("[1/3] 글로벌 N-gram 탐색")
    custom_ngram_tags = build_global_ngram_dictionary(
        rows_df=rows_df,
        kiwi=kiwi_base,
        stopword_set=stopword_set,
        threshold=ngram_threshold,
    )
    print(f"N-gram 후보 등록 수: {len(custom_ngram_tags)}")

    kiwi = build_kiwi_analyzer(
        custom_words=custom_words,
        ngram_words=custom_ngram_tags.keys(),
    )

    print("[2/3] source별 noun_data 생성")
    result = analyze_fulltext_rows(
        rows_df=rows_df,
        kiwi=kiwi,
        stopword_set=stopword_set,
        custom_ngram_tags=custom_ngram_tags,
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
    )

    print("[3/3] 저장")
    if save_output:
        for _source, cfg in SOURCE_CONFIG.items():
            output_key = cfg["output_key"]
            df = result.get(output_key, pd.DataFrame())
            out_path = output_dir / f"{output_key}.csv"
            save_csv_safely(df, out_path)
            print(f"- {output_key}: {df.shape} -> {out_path}")

        ngram_df = pd.DataFrame([
            {"word": word, "pos": pos}
            for word, pos in custom_ngram_tags.items()
        ])
        save_csv_safely(ngram_df, output_dir / "custom_ngram_dictionary.csv")

    print("[TEXT ANALYSIS DONE]")
    return result


def run_text_analysis_for_job(
    job_id: str,
    jobs_output_dir: Path = Path("outputs/jobs"),
    periods: Iterable[str] = ("t", "t_minus_1"),
    **kwargs,
) -> Dict[str, Dict[str, pd.DataFrame]]:
    """outputs/jobs/{job_id}/{period}/text 폴더를 기준으로 t/t-1 둘 다 분석."""
    jobs_output_dir = Path(jobs_output_dir)
    job_dir = jobs_output_dir / job_id

    all_results = {}
    for period_type in periods:
        input_dir = job_dir / period_type / "text"
        output_dir = job_dir / period_type / "text_analysis"
        all_results[period_type] = run_text_analysis(
            input_dir=input_dir,
            output_dir=output_dir,
            **kwargs,
        )

    return all_results


